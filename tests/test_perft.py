import pytest

from chess.board import Board
from chess.rules import generate_legal_moves


def perft(board: Board, depth: int) -> int:
    if depth == 0:
        return 1
    count = 0
    for move in generate_legal_moves(board, board.turn):
        board.make_move(move)
        count += perft(board, depth - 1)
        board.undo_move()
    return count


@pytest.mark.parametrize(
    "depth, expected",
    [(1, 20), (2, 400), (3, 8902), (4, 197281)],
)
def test_perft_start_position(depth, expected):
    assert perft(Board.starting_position(), depth) == expected


@pytest.mark.parametrize(
    "depth, expected",
    [(1, 14), (2, 191), (3, 2812), (4, 43238)],
)
def test_perft_position_3(depth, expected):
    board = Board.from_fen("8/2p5/3p4/KP5r/1R3p1k/8/4P1P1/8 w - - 0 1")
    assert perft(board, depth) == expected


